using System.Text.Json;

namespace ClawPal.Companion;

// A time zone the display can use. Preset labels are translation keys; others name their IANA zone or POSIX rule.
public sealed record TimeZoneChoice(string Posix, string? Iana = null, string? LabelKey = null)
{
    public override string ToString() => LabelKey is not null ? L.Text(LabelKey) : Iana is not null ? L.Text("location_time_zone_value", Iana.Replace('_', ' ')) : L.Text("saved_time_zone_value", Posix);
}

public static class TimeZones
{
    public static readonly TimeZoneChoice[] Presets = [
        new("UTC0", LabelKey: "utc"), new("CET-1CEST,M3.5.0,M10.5.0/3", LabelKey: "central_europe_warsaw_berlin"),
        new("GMT0BST,M3.5.0/1,M10.5.0", LabelKey: "uk_ireland"), new("EET-2EEST,M3.5.0/3,M10.5.0/4", LabelKey: "eastern_europe"),
        new("EST5EDT,M3.2.0,M11.1.0", LabelKey: "us_canada_eastern"), new("CST6CDT,M3.2.0,M11.1.0", LabelKey: "us_canada_central"),
        new("MST7MDT,M3.2.0,M11.1.0", LabelKey: "us_canada_mountain"), new("PST8PDT,M3.2.0,M11.1.0", LabelKey: "us_canada_pacific"),
        new("IST-5:30", LabelKey: "india"), new("CST-8", LabelKey: "china_singapore"), new("JST-9", LabelKey: "japan_korea"),
        new("AEST-10AEDT,M10.1.0,M4.1.0/3", LabelKey: "australia_sydney_melbourne"), new("AEST-10", LabelKey: "australia_brisbane"),
        new("NZST-12NZDT,M9.5.0,M4.1.0/3", LabelKey: "new_zealand") ];

    // Generated by scripts/generate_timezones.py from the IANA tz database.
    private static readonly Lazy<Dictionary<string, string>> table = new(() => {
        using var stream = typeof(TimeZones).Assembly.GetManifestResourceStream("ClawPal.TimeZones") ?? throw new InvalidDataException("Missing time zone table.");
        using var document = JsonDocument.Parse(stream);
        return document.RootElement.GetProperty("zones").EnumerateObject().ToDictionary(p => p.Name, p => p.Value.GetString()!, StringComparer.Ordinal);
    });

    // The POSIX rule for an IANA zone such as "America/Sao_Paulo", or null when the display cannot represent it exactly.
    public static string? FromIana(string? iana) => iana is not null && table.Value.TryGetValue(iana, out var posix) ? posix : null;

    // Presets plus the current zone when it is not one of them; the current zone is selected.
    internal static void Fill(ChoiceBox box, string posix, string? iana = null)
    {
        var current = Presets.FirstOrDefault(z => z.Posix == posix) ?? new TimeZoneChoice(posix, iana);
        box.Items.Clear(); box.Items.AddRange(Presets);
        if (!Presets.Contains(current)) box.Items.Add(current);
        box.SelectedIndex = box.Items.IndexOf(current);
    }

    // Selects the zone of a chosen place. Returns false when the place's zone is unknown, leaving the selection alone.
    internal static bool SelectFor(ChoiceBox box, Place place)
    {
        if (FromIana(place.Timezone) is not { } posix) return false;
        Fill(box, posix, place.Timezone);
        return true;
    }
}
