"""Build LVGL fonts covering every display catalog, keeping symbol fallbacks."""
from pathlib import Path
import argparse,json,subprocess
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--node',default='node');parser.add_argument('--converter',type=Path,required=True);args=parser.parse_args()
characters=set(range(0x20,0x180))|{0x2010,0x2011,0x2013,0x2014,0x2018,0x2019,0x201c,0x201d,0x2026,0x20ac}
required=set()
for path in (ROOT/'languages').glob('*.json'):
    pack=json.loads(path.read_text(encoding='utf-8'))
    required.update(ord(c) for text in pack['display'].values() for c in text if ord(c)>=32)
characters.update(required)
query="const o=require(require.resolve('opentype.js',{paths:[process.argv[1]]}));const f=o.loadSync(process.argv[2]);process.stdout.write(JSON.stringify(Object.keys(f.tables.cmap.glyphIndexMap).map(Number)));"
available=set(json.loads(subprocess.check_output([args.node,'-e',query,str(args.converter.parent),str(ROOT/'assets/fonts/Montserrat-Medium.ttf')],text=True)))
if required-available:raise ValueError('Font has no glyphs for: '+''.join(chr(c) for c in sorted(required-available)))
characters.intersection_update(available)
font_range=','.join(hex(c) for c in sorted(characters))
names=[]
for size in [14,16,20,24,32,48]:
    name=f'buddy_language_font_{size}';names.append(name)
    target=ROOT/'firmware/main/language'/f'{name}.c'
    subprocess.run([args.node,str(args.converter),'--size',str(size),'--bpp','4','--no-compress','--no-prefilter','--font','assets/fonts/Montserrat-Medium.ttf','--range',font_range,'--format','lvgl','--lv-include','lvgl.h','--lv-font-name',name,'--output',target.relative_to(ROOT).as_posix()],check=True,cwd=ROOT)
    text=target.read_text(encoding='utf-8').replace('.fallback = NULL',f'.fallback = &lv_font_montserrat_{size}')
    target.write_text('/* Montserrat: SIL OFL 1.1, see assets/fonts/OFL.txt. Generated by scripts/generate_language_fonts.py. */\n'+text,encoding='utf-8',newline='\n')
(ROOT/'firmware/main/language/buddy_language_fonts.h').write_text('#pragma once\n#include "lvgl.h"\n'+'\n'.join(f'LV_FONT_DECLARE({name});' for name in names)+'\n',encoding='utf-8',newline='\n')
(ROOT/'firmware/main/language/font_coverage.json').write_text(json.dumps(sorted(characters))+'\n',encoding='utf-8')
print(f'Generated six font sizes, {len(characters)} requested characters')
