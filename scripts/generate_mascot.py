#!/usr/bin/env python3
"""Losslessly encode the supplied 48px RGBA sprite sheets for LVGL 8.

Python standard library only. No quantization, interpolation, color correction,
or source-image rewriting. --check validates generated files without editing.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "mascot"
DEST = ROOT / "firmware" / "main" / "assets"
STATES = ("happy", "idle", "thinking", "working", "sleeping", "carrying", "typing", "music", "error", "sunny", "cloudy", "rainy", "night")
SIZE, COLUMNS, ROWS = 48, 8, 6


def paeth(a, b, c):
    p = a + b - c
    distances = (abs(p - a), abs(p - b), abs(p - c))
    return (a, b, c)[distances.index(min(distances))]


def read_rgba_png(path):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"Not a PNG: {path}")
    pos, chunks, dimensions = 8, [], None
    while pos < len(data):
        length = struct.unpack_from(">I", data, pos)[0]
        kind = data[pos + 4:pos + 8]
        payload = data[pos + 8:pos + 8 + length]
        crc = struct.unpack_from(">I", data, pos + 8 + length)[0]
        if zlib.crc32(kind + payload) != crc:
            raise ValueError(f"PNG CRC mismatch: {path}")
        if kind == b"IHDR":
            width, height, depth, color, compression, filtering, interlace = struct.unpack(">IIBBBBB", payload)
            if (depth, color, compression, filtering, interlace) != (8, 6, 0, 0, 0):
                raise ValueError("Expected the supplied non-interlaced 8-bit RGBA PNGs")
            dimensions = (width, height)
        elif kind == b"IDAT":
            chunks.append(payload)
        elif kind == b"IEND":
            break
        pos += length + 12
    if dimensions != (SIZE * COLUMNS, SIZE * ROWS):
        raise ValueError(f"Incorrect sheet dimensions: {dimensions}")
    width, height = dimensions
    raw = zlib.decompress(b"".join(chunks))
    stride = width * 4
    if len(raw) != (stride + 1) * height:
        raise ValueError("Incorrect decompressed PNG size")
    previous, pixels = bytearray(stride), bytearray()
    for y in range(height):
        start = y * (stride + 1)
        kind, row = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        if kind > 4:
            raise ValueError(f"Unsupported PNG row filter {kind}")
        for i in range(stride):
            left = row[i - 4] if i >= 4 else 0
            above = previous[i]
            corner = previous[i - 4] if i >= 4 else 0
            prediction = (0, left, above, (left + above) // 2, paeth(left, above, corner))[kind]
            row[i] = (row[i] + prediction) & 255
        pixels.extend(row)
        previous = row
    return pixels


def generate():
    sheets = {state: read_rgba_png(SOURCE / f"crab_{state}_sheet.png") for state in STATES}
    actual_colors = set()
    for data in sheets.values():
        actual_colors.update(tuple(data[i:i+4]) for i in range(0,len(data),4))
    unique, indices, checked_pixels = [], {}, 0
    for state, pixels in sheets.items():
        colors=sorted(set(tuple(pixels[i:i+4]) for i in range(0,len(pixels),4)))
        if len(colors)>16: raise ValueError(f"{state} exceeds the lossless 4-bit palette")
        palette=colors+[(0,0,0,0)]*(16-len(colors))
        lookup={rgba:index for index,rgba in reversed(list(enumerate(palette)))}
        palette_bytes=bytes(channel for r,g,b,a in palette for channel in (b,g,r,a))
        indices[state] = []
        for number in range(COLUMNS * ROWS):
            frame = []
            origin_x, origin_y = (number % COLUMNS) * SIZE, (number // COLUMNS) * SIZE
            for y in range(SIZE):
                for x in range(SIZE):
                    offset = ((origin_y + y) * SIZE * COLUMNS + origin_x + x) * 4
                    frame.append(tuple(pixels[offset:offset + 4]))
            encoded = palette_bytes + bytes((lookup[frame[i]] << 4) | lookup[frame[i + 1]]
                                             for i in range(0, len(frame), 2))
            # Decode every pixel independently from the actual LVGL byte layout.
            reconstructed = [tuple(encoded[(encoded[64 + i // 2] >> (4 if i % 2 == 0 else 0) & 15) * 4 + j]
                                   for j in (2, 1, 0, 3)) for i in range(SIZE * SIZE)]
            if reconstructed != frame:
                raise AssertionError(f"Lossless roundtrip failed: {state} {number}")
            checked_pixels += len(frame)
            if encoded not in unique:
                unique.append(encoded)
            indices[state].append(unique.index(encoded))

    source = ["/* Generated by scripts/generate_mascot.py; do not hand edit. */",
              '#include "buddy_mascot.h"', ""]
    for index, data in enumerate(unique):
        source.append(f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t frame_{index}[] = {{")
        source.extend("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + "," for i in range(0, len(data), 24))
        source.extend(["};", ""])
    source.append("const lv_img_dsc_t buddy_mascot_frames[BUDDY_MASCOT_STATE_COUNT][BUDDY_MASCOT_FRAME_COUNT] = {")
    for state in STATES:
        source.append(f"    [BUDDY_MASCOT_{state.upper()}] = {{")
        for index in indices[state]:
            source.append("        { .header = { .cf = LV_IMG_CF_INDEXED_4BIT, .always_zero = 0, .w = 48, .h = 48 }, "
                          f".data_size = sizeof(frame_{index}), .data = frame_{index} }},")
        source.append("    },")
    source.extend(["};", ""])

    manifest = {
        "source": "User-supplied krabik_assets and additional project mascot sheets, 2026-10-06",
        "layout": {"frameWidth": SIZE, "frameHeight": SIZE, "columns": COLUMNS, "rows": ROWS,
                   "frameOrder": "row-major", "framesPerState": COLUMNS * ROWS},
        "encoding": "LVGL 8 INDEXED_4BIT with exact BGRA palette; identical frame buffers shared",
        "playback": {"fps": 10, "timing": "Implementation choice; source assets did not include timing metadata"},
        "sourceColorsIncludingTransparency": len(actual_colors),
        "uniqueEncodedFrames": len(unique),
        "encodedPixelAndPaletteBytes": sum(map(len, unique)),
        "verifiedRoundtripPixels": checked_pixels,
        "files": {p.name: {"sha256": hashlib.sha256(p.read_bytes()).hexdigest(), "bytes": p.stat().st_size}
                  for p in sorted(SOURCE.iterdir()) if p.suffix in (".png", ".json") and p.name != "manifest.json"},
    }
    return {DEST / "buddy_mascot.c": "\n".join(source),
            SOURCE / "manifest.json": json.dumps(manifest, indent=2) + "\n"}, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify source pixels and generated outputs without writing")
    args = parser.parse_args()
    outputs, manifest = generate()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Generated file is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print(json.dumps({key: manifest[key] for key in ("uniqueEncodedFrames", "encodedPixelAndPaletteBytes", "verifiedRoundtripPixels")}))


if __name__ == "__main__":
    main()

