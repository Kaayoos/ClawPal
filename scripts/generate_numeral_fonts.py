"""Build Studio's light numerals: Montserrat Light digits that fall back to the Medium fonts for anything else."""
from pathlib import Path
import argparse,re,subprocess
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--node',default='node');parser.add_argument('--converter',type=Path,required=True);args=parser.parse_args()
# Digits and the punctuation of times, temperatures and percentages; letters stay Medium through the fallback.
# The 96 px clock face keeps the clock font's own set.
numbers='0x20,0x25,0x2b-0x3a,0xb0'
sizes={96:('buddy_clock_font','buddy_clock_font.h','firmware/main/assets/buddy_clock_font.c','0x2d,0x30-0x3a'),
       48:('buddy_language_font_48','buddy_language_fonts.h','firmware/main/language/buddy_language_font_48.c',numbers),
       32:('buddy_language_font_32','buddy_language_fonts.h','firmware/main/language/buddy_language_font_32.c',numbers),
       24:('buddy_language_font_24','buddy_language_fonts.h','firmware/main/language/buddy_language_font_24.c',numbers),
       # Studio's home clock has no Medium twin; it only ever shows a time or its "--:--" placeholder.
       128:(None,None,None,'0x2d,0x30-0x3a')}
METRIC=re.compile(r'\.(line_height|base_line) = (\d+),')
names=[]
for size,(fallback,header,twin,font_range) in sizes.items():
    name=f'buddy_numeral_font_{size}';names.append(name)
    target=ROOT/'firmware/main/assets'/f'{name}.c'
    subprocess.run([args.node,str(args.converter),'--size',str(size),'--bpp','4','--no-compress','--no-prefilter','--font','assets/fonts/Montserrat-Light.ttf','--range',font_range,'--format','lvgl','--lv-include','lvgl.h','--lv-font-name',name,'--output',target.relative_to(ROOT).as_posix()],check=True,cwd=ROOT)
    text=target.read_text(encoding='utf-8')
    if text.count('.fallback = NULL')!=1 or len(METRIC.findall(text))!=2:raise ValueError(f'{target}: unexpected converter output')
    if twin:
        text=text.replace('.fallback = NULL',f'.fallback = &{fallback}').replace('#endif\n',f'#endif\n#include "{header}"\n',1)
        # Sharing the Medium twin's line metrics keeps every label exactly where its layout put it.
        metrics=dict(METRIC.findall((ROOT/twin).read_text(encoding='utf-8')))
        text=METRIC.sub(lambda m:f'.{m[1]} = {metrics[m[1]]},',text)
    target.write_text('/* Copyright 2011 The Montserrat Project Authors (https://github.com/JulietaUla/Montserrat).\n'
                      ' * Font data licensed under SIL OFL 1.1; see assets/fonts/OFL.txt.\n'
                      ' * Generated by scripts/generate_numeral_fonts.py. */\n'+text,encoding='utf-8',newline='\n')
(ROOT/'firmware/main/assets/buddy_numeral_fonts.h').write_text('#pragma once\n#include "lvgl.h"\n\n/* Montserrat Light numerals for themes with light_numerals; other glyphs fall back to Medium. */\n'+
    '\n'.join(f'LV_FONT_DECLARE({name});' for name in names)+'\n',encoding='utf-8',newline='\n')
print(f'Generated {len(names)} light numeral sizes')
