"""Validate UTF-8 catalogs and compile the display strings. Python 3.10+, stdlib only."""
from pathlib import Path
import argparse,json,re,sys
ROOT=Path(__file__).resolve().parents[1]
PRINTF=re.compile(r'%(?:[-+ #0]*)(?:\d+)?(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')
DOTNET=re.compile(r'(?<!\{)\{(\d+)(?:,-?\d+)?(?::([^{}]*))?\}(?!\})')
def read_catalogs(root):
    files=sorted((root/'languages').glob('*.json'))
    packs=[json.loads(p.read_text(encoding='utf-8-sig')) for p in files]
    by_code={p['meta']['code']:p for p in packs}
    if len(by_code)!=len(packs) or 'en' not in by_code:raise ValueError('Unique language codes and en.json are required')
    english=by_code['en']
    for path,pack in zip(files,packs):
        meta=pack['meta'];code=meta['code']
        if not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})?',code) or path.stem!=code or len(code.encode())>15:raise ValueError(f'{path}: invalid language code')
        if meta.get('direction')!='ltr':raise ValueError(f'{code}: this display currently supports left-to-right scripts')
        if not meta.get('name') or not meta.get('culture'):raise ValueError(f'{code}: missing language metadata')
        # Theme variants override base keys only; Studio replaces the crab's voice with a calmer one.
        for section in ['companion','display','companion_studio','display_studio']:
            base=section.split('_')[0]
            if section not in pack and section.endswith('_studio'):continue
            if set(pack[section])-set(english[base]):raise ValueError(f'{code}/{section}: unknown translation key')
            for key,text in pack[section].items():
                if not re.fullmatch('[a-z][a-z0-9_]*|[0-9][a-z0-9_]*',key) or not isinstance(text,str) or not text or '\0' in text:raise ValueError(f'{code}/{section}/{key}: invalid value')
                if len(text.encode())>4096:raise ValueError(f'{code}/{key}: translation is too long')
                original=english[base][key]
                if base=='display' and key in english.get('formats',{}).get('display',[]):
                    if '%' in PRINTF.sub('',text):raise ValueError(f'{code}/{key}: unsupported printf placeholder')
                    formats=lambda s:[m[0] for m in PRINTF.finditer(s) if m[0]!='%%']
                    if formats(text)!=formats(original):raise ValueError(f'{code}/{key}: printf types/order must match English')
                elif base=='display' and text.count('%')!=original.count('%'):raise ValueError(f'{code}/{key}: literal percent count must match English')
                elif base=='companion' and sorted(DOTNET.findall(text))!=sorted(DOTNET.findall(original)):raise ValueError(f'{code}/{key}: .NET placeholders must match English')
            missing=set(english.get(section,{}))-set(pack[section])
            if missing:print(f'{code}/{section}: {len(missing)} missing keys use English')
    return [english]+[p for p in packs if p is not english]
def generate(root,check=False):
    packs=read_catalogs(root);keys=sorted(packs[0]['display'])
    header=['// Generated by scripts/generate_languages.py. Edit languages/*.json instead.','#pragma once','typedef enum {']
    header += ['    BT_'+key.upper()+',' for key in keys]
    header += ['    BT_COUNT','} buddy_text_key_t;','extern const char *const buddy_language_codes[];','extern const unsigned buddy_language_count;','extern const char *const buddy_language_texts[][BT_COUNT];',
               '/* Studio theme wording; NULL keeps the base text. */','extern const char *const buddy_language_studio_texts[][BT_COUNT];','']
    source=['// Generated by scripts/generate_languages.py.','#include "buddy_language_data.h"',f'const unsigned buddy_language_count = {len(packs)};', 'const char *const buddy_language_codes[] = {'+', '.join(json.dumps(p['meta']['code']) for p in packs)+'};','']
    for i,pack in enumerate(packs):
        for key in keys:source.append('static const char text_'+str(i)+'_'+key+'[] = '+json.dumps(pack['display'].get(key,packs[0]['display'][key]),ensure_ascii=False)+';')
    source.append('const char *const buddy_language_texts[][BT_COUNT] = {')
    for i,pack in enumerate(packs):
        source+=['    { /* '+pack['meta']['code']+' */']
        source+=['        text_'+str(i)+'_'+key+',' for key in keys]
        source+=['    },']
    source+=['};','']
    for i,pack in enumerate(packs):
        for key in keys:
            if key in pack.get('display_studio',{}):source.append('static const char studio_'+str(i)+'_'+key+'[] = '+json.dumps(pack['display_studio'][key],ensure_ascii=False)+';')
    source.append('const char *const buddy_language_studio_texts[][BT_COUNT] = {')
    for i,pack in enumerate(packs):
        source+=['    { /* '+pack['meta']['code']+' */']
        source+=['        [BT_'+key.upper()+'] = studio_'+str(i)+'_'+key+',' for key in keys if key in pack.get('display_studio',{})]
        source+=['    },']
    source+=['};','']
    output=root/'firmware/main/language';output.mkdir(exist_ok=True)
    for filename,lines in [('buddy_language_data.h',header),('buddy_language_data.c',source)]:
        value='\n'.join(lines);path=output/filename
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=value:raise ValueError(f'{path}: stale generated catalog; run scripts/generate_languages.py')
        else:path.write_text(value,encoding='utf-8',newline='\n')
    coverage=output/'font_coverage.json'
    if coverage.exists():
        glyphs=set(json.loads(coverage.read_text()))
        required={ord(c) for p in packs for section in ['display','display_studio'] for text in p.get(section,{}).values() for c in text if ord(c)>=32}
        if required-glyphs:raise ValueError('Rebuild language fonts; missing glyphs: '+''.join(chr(c) for c in sorted(required-glyphs)))
    # Every referenced key must exist. This also catches accidentally removed translations.
    for path in (root/'companion').glob('*.cs'):
        for key in re.findall(r'L\.Text\("([^"]+)"',path.read_text(encoding='utf-8')):
            if key not in packs[0]['companion']:raise ValueError(f'{path.name}: missing companion key {key}')
    print(f'{len(packs)} language(s); {len(packs[0]["companion"])} PC strings; {len(keys)} display strings validated')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--root',type=Path,default=ROOT)
    args=parser.parse_args()
    try:generate(args.root,args.check)
    except (ValueError,KeyError,json.JSONDecodeError) as e:sys.exit(str(e))
