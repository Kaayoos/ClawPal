"""Validate themes/themes.json and compile the display palettes. Python 3.10+, stdlib only."""
from pathlib import Path
import argparse,json,re,sys
ROOT=Path(__file__).resolve().parents[1]
COLORS=['bg','surface','pressed','text','muted','rule','accent','warning','clock_bg','clock_text','weather_app','weather_mark']
SHAPE={'border_w':(1,4),'gauge_div':(6,30),'ring_div':(10,60),'chart_w':(1,4),'track_h':(2,6),'motion_pct':(0,100)}
FLAGS=['mascot','accents','outlined_cards','light_numerals','prompt_tile','app_flourish']
def rgb(value,where):
    if not isinstance(value,str) or not re.fullmatch('#[0-9A-Fa-f]{6}',value):raise ValueError(f'{where}: colours are #RRGGBB')
    return int(value[1:],16)
def luminance(c):
    channel=lambda v:v/12.92 if v<=0.03928 else ((v+0.055)/1.055)**2.4
    r,g,b=((c>>16)&255)/255,((c>>8)&255)/255,(c&255)/255
    return 0.2126*channel(r)+0.7152*channel(g)+0.0722*channel(b)
def contrast(a,b):
    x,y=sorted([luminance(a),luminance(b)],reverse=True);return (x+0.05)/(y+0.05)
# The panels are RGB565: a hairline or surface that rounds onto the background disappears.
def rgb565(c):return ((c>>19)&31,(c>>10)&63,(c>>3)&31)
def check_theme(theme,accents):
    name=theme['id']
    if not re.fullmatch('[a-z]{2,15}',name):raise ValueError(f'{name}: theme ids are 2-15 lowercase letters')
    if set(theme['colors'])!=set(COLORS):raise ValueError(f'{name}: colour roles must be exactly '+', '.join(COLORS))
    if set(theme['shape'])!=set(SHAPE) or set(theme['flags'])!=set(FLAGS):raise ValueError(f'{name}: shape and flag keys are fixed')
    c={k:rgb(v,f'{name}/{k}') for k,v in theme['colors'].items()}
    for key,(low,high) in SHAPE.items():
        if not isinstance(theme['shape'][key],int) or not low<=theme['shape'][key]<=high:raise ValueError(f'{name}/{key}: expected {low}..{high}')
    if any(not isinstance(v,bool) for v in theme['flags'].values()):raise ValueError(f'{name}: flags are true or false')
    inks=[c['accent']]+([rgb(a['color'],a['id']) for a in accents] if theme['flags']['accents'] else [])
    for label,ink,ground,minimum in [('text',c['text'],c['bg'],7),('text',c['text'],c['surface'],7),('muted',c['muted'],c['bg'],4.5),('warning',c['warning'],c['bg'],3),('clock_text',c['clock_text'],c['clock_bg'],7)]+[('accent',ink,c['bg'],3) for ink in inks]:
        if contrast(ink,ground)<minimum:raise ValueError(f'{name}/{label}: contrast {contrast(ink,ground):.2f} is below {minimum}')
    for a,b in [('rule','bg'),('surface','bg'),('pressed','surface'),('rule','surface')]:
        if rgb565(c[a])==rgb565(c[b]):raise ValueError(f'{name}: {a} and {b} are identical on an RGB565 panel')
    return c
def generate(root,check=False):
    data=json.loads((root/'themes/themes.json').read_text(encoding='utf-8'))
    accents,themes=data['accents'],data['themes']
    ids=[t['id'] for t in themes];accent_ids=[a['id'] for a in accents]
    if not themes or ids[0]!='crab' or len(set(ids))!=len(ids):raise ValueError('Themes need unique ids and crab first; older settings default to it')
    if not accents or len(set(accent_ids))!=len(accent_ids) or any(not re.fullmatch('[a-z]{2,15}',a) for a in accent_ids):raise ValueError('Accent ids are unique, 2-15 lowercase letters')
    header=['// Generated by scripts/generate_themes.py. Edit themes/themes.json instead.','#pragma once','#include <stdbool.h>','#include <stdint.h>',
            'typedef enum { '+' '.join(f'BUDDY_THEME_{i.upper()},' for i in ids)+' BUDDY_THEME_COUNT } buddy_theme_id_t;',
            'typedef enum { '+' '.join(f'BUDDY_ACCENT_{i.upper()},' for i in accent_ids)+' BUDDY_ACCENT_COUNT } buddy_accent_id_t;',
            'typedef struct {','    uint32_t '+', '.join(COLORS)+';','    uint8_t '+', '.join(SHAPE)+';','    bool '+', '.join(FLAGS)+';','} buddy_theme_t;']
    source=['// Generated by scripts/generate_themes.py.','#include "buddy_theme_data.h"']
    rows=[]
    for theme in themes:
        c=check_theme(theme,accents)
        values=[f'0x{c[k]:06X}' for k in COLORS]+[str(theme['shape'][k]) for k in SHAPE]+['true' if theme['flags'][k] else 'false' for k in FLAGS]
        header.append(f'#define BUDDY_THEME_{theme["id"].upper()}_VALUES {{ '+', '.join(values)+' }')
        rows.append(f'BUDDY_THEME_{theme["id"].upper()}_VALUES')
    header+=['extern const buddy_theme_t buddy_themes[BUDDY_THEME_COUNT];','extern const uint32_t buddy_theme_accents[BUDDY_ACCENT_COUNT];',
             'extern const char *const buddy_theme_ids[BUDDY_THEME_COUNT];','extern const char *const buddy_accent_ids[BUDDY_ACCENT_COUNT];','']
    source+=['const buddy_theme_t buddy_themes[BUDDY_THEME_COUNT] = { '+', '.join(rows)+' };',
             'const uint32_t buddy_theme_accents[BUDDY_ACCENT_COUNT] = { '+', '.join(f'0x{rgb(a["color"],a["id"]):06X}' for a in accents)+' };',
             'const char *const buddy_theme_ids[BUDDY_THEME_COUNT] = { '+', '.join(json.dumps(i) for i in ids)+' };',
             'const char *const buddy_accent_ids[BUDDY_ACCENT_COUNT] = { '+', '.join(json.dumps(i) for i in accent_ids)+' };','']
    output=root/'firmware/main/ui'
    for filename,lines in [('buddy_theme_data.h',header),('buddy_theme_data.c',source)]:
        value='\n'.join(lines);path=output/filename
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=value:raise ValueError(f'{path}: stale generated themes; run scripts/generate_themes.py')
        else:path.write_text(value,encoding='utf-8',newline='\n')
    print(f'{len(themes)} theme(s); {len(accents)} accent(s) validated')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--root',type=Path,default=ROOT)
    args=parser.parse_args()
    try:generate(args.root,args.check)
    except (ValueError,KeyError,json.JSONDecodeError) as e:sys.exit(str(e))
