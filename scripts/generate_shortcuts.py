"""Validate shortcuts/shortcuts.json and compile the Shortcuts icons and colours for the display. Python 3.10+, stdlib only.

The companion embeds the same file and draws the icons itself, so the editor preview matches the display."""
from pathlib import Path
import argparse,json,re,sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from generate_themes import rgb,contrast
ROOT=Path(__file__).resolve().parents[1]
# l: line x1 y1 x2 y2. b/f: outlined/filled box x y w h radius (-1 = round). a: arc cx cy r start end (degrees, clockwise from 3 o'clock). p: polyline x y x y ...
SHAPES={'l':4,'b':5,'f':5,'a':5}
# The page and the starter deck name these directly.
REQUIRED=['mic','mic_off','speaker','speaker_off','volume_down','volume_up','play_pause','play','pause','next','previous','lock','screenshot','grid','app','globe','folder','keyboard']
def check_shape(shape,where):
    if not isinstance(shape,list) or not shape or shape[0] not in [*SHAPES,'p']:raise ValueError(f'{where}: unknown shape')
    kind,values=shape[0],shape[1:]
    if any(not isinstance(v,int) for v in values):raise ValueError(f'{where}: values are whole numbers')
    if kind=='p':
        if len(values)<4 or len(values)%2:raise ValueError(f'{where}: a polyline needs two or more x,y points')
        points=values
    else:
        if len(values)!=SHAPES[kind]:raise ValueError(f'{where}: {kind} takes {SHAPES[kind]} values')
        if kind=='a':
            if not all(0<=v<=100 for v in values[:3]) or not all(0<=v<360 for v in values[3:]):raise ValueError(f'{where}: arcs use 0..100 and angles 0..359')
            return kind,values
        points=values[:4] if kind!='l' else values
        if kind in 'bf' and (values[2]<=0 or values[3]<=0 or values[0]+values[2]>100 or values[1]+values[3]>100 or not -1<=values[4]<=50):raise ValueError(f'{where}: box outside the grid')
    if not all(0<=v<=100 for v in points):raise ValueError(f'{where}: coordinates are 0..100')
    return kind,values
def generate(root,check=False):
    data=json.loads((root/'shortcuts/shortcuts.json').read_text(encoding='utf-8'))
    themes=json.loads((root/'themes/themes.json').read_text(encoding='utf-8'))['themes']
    colors,icons=data['colors'],data['icons']
    color_ids=[c['id'] for c in colors];icon_ids=[i['id'] for i in icons]
    pattern=re.compile('[a-z][a-z0-9_]{1,15}')
    for ids,label in [(color_ids,'colour'),(icon_ids,'icon')]:
        if len(set(ids))!=len(ids) or any(not pattern.fullmatch(i) for i in ids):raise ValueError(f'{label} ids are unique, 2-16 characters a-z, 0-9 and _')
    if color_ids[0]!='accent' or 'color' in colors[0]:raise ValueError('The first colour is accent, which follows the look')
    if not 2<=len(colors)<=16 or not 1<=len(icons)<=64:raise ValueError('2-16 colours and 1-64 icons')
    values=[]
    for c in colors[1:]:
        value=rgb(c.get('color'),c['id']);values.append(value)
        for theme in themes:
            for role in ['bg','surface']:
                ground=rgb(theme['colors'][role],theme['id'])
                if contrast(value,ground)<3:raise ValueError(f'{c["id"]}: contrast {contrast(value,ground):.2f} on {theme["id"]}/{role} is below 3')
    missing=[i for i in REQUIRED if i not in icon_ids]
    if missing:raise ValueError('Missing icons: '+', '.join(missing))
    shapes,numbers,rows=[],[],[]
    for icon in icons:
        on=icon.get('on')
        if on is not None and (on not in icon_ids or on==icon['id']):raise ValueError(f'{icon["id"]}: "on" names another icon')
        if not 1<=len(icon['shapes'])<=16:raise ValueError(f'{icon["id"]}: 1-16 shapes')
        first=len(shapes)
        for n,shape in enumerate(icon['shapes']):
            kind,v=check_shape(shape,f'{icon["id"]}[{n}]')
            shapes.append(f"{{'{kind}',{len(v)},{len(numbers)}}}");numbers+=v
        rows.append(f'{{{json.dumps(icon["id"])},{first},{len(icon["shapes"])},{icon_ids.index(on) if on else -1}}}')
    header=['// Generated by scripts/generate_shortcuts.py. Edit shortcuts/shortcuts.json instead.','#pragma once','#include <stdint.h>',
            'typedef enum { '+' '.join(f'BUDDY_SHORTCUT_ICON_{i.upper()},' for i in icon_ids)+' BUDDY_SHORTCUT_ICON_COUNT } buddy_shortcut_icon_id_t;',
            f'#define BUDDY_SHORTCUT_COLOR_COUNT {len(colors)}',
            '/* kind is l, b, f, a or p; values index buddy_shortcut_values. */',
            'typedef struct { char kind; uint8_t count; uint16_t first; } buddy_shortcut_shape_t;',
            'typedef struct { const char *id; uint16_t first; uint8_t count; int8_t on; } buddy_shortcut_icon_t;',
            'extern const buddy_shortcut_shape_t buddy_shortcut_shapes[];','extern const int16_t buddy_shortcut_values[];',
            'extern const buddy_shortcut_icon_t buddy_shortcut_icons[BUDDY_SHORTCUT_ICON_COUNT];',
            '/* Colour 0 is the look\'s accent; its entry here is unused. */',
            'extern const char *const buddy_shortcut_color_ids[BUDDY_SHORTCUT_COLOR_COUNT];','extern const uint32_t buddy_shortcut_colors[BUDDY_SHORTCUT_COLOR_COUNT];','']
    source=['// Generated by scripts/generate_shortcuts.py.','#include "buddy_shortcut_data.h"',
            'const buddy_shortcut_shape_t buddy_shortcut_shapes[] = { '+', '.join(shapes)+' };',
            'const int16_t buddy_shortcut_values[] = { '+', '.join(map(str,numbers))+' };',
            'const buddy_shortcut_icon_t buddy_shortcut_icons[BUDDY_SHORTCUT_ICON_COUNT] = { '+', '.join(rows)+' };',
            'const char *const buddy_shortcut_color_ids[BUDDY_SHORTCUT_COLOR_COUNT] = { '+', '.join(json.dumps(i) for i in color_ids)+' };',
            'const uint32_t buddy_shortcut_colors[BUDDY_SHORTCUT_COLOR_COUNT] = { 0, '+', '.join(f'0x{v:06X}' for v in values)+' };','']
    output=root/'firmware/main/ui'
    for filename,lines in [('buddy_shortcut_data.h',header),('buddy_shortcut_data.c',source)]:
        value='\n'.join(lines);path=output/filename
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=value:raise ValueError(f'{path}: stale generated shortcuts; run scripts/generate_shortcuts.py')
        else:path.write_text(value,encoding='utf-8',newline='\n')
    print(f'{len(icons)} icon(s); {len(colors)} colour(s) validated')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--root',type=Path,default=ROOT)
    args=parser.parse_args()
    try:generate(args.root,args.check)
    except (ValueError,KeyError,json.JSONDecodeError) as e:sys.exit(str(e))
